        '      {"ResultFeature", "pgPass", "p:showlooplevel", "T", "30", "valueMatrix", "1|3,''on'',''off'',''off''"},'
        '      {"ResultFeature", "pgPass", "p:looplevel", "T", "30", "valueMatrix", "1|1,''3''"},'
        '    };'
        '    URI archiveUri = URI.create("jar:" + file.toUri());'
        '    try (FileSystem archive = FileSystems.newFileSystem(archiveUri, Collections.emptyMap())) {'
        '      Path modelFile = archive.getPath("/dmodel.xml");'
