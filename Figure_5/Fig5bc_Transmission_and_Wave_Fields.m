function writeResultSelectionCode(fileName)
    [file, message] = fopen(fileName, 'w', 'n', 'UTF-8');
    if file < 0
        error('ComsolExport:WriteCode', '%s', message);
    end
    closeFile = onCleanup(@() fclose(file));
    code = {
        'import java.io.InputStream;'
        'import java.io.OutputStream;'
        'import java.net.URI;'
        'import java.nio.file.FileSystem;'
        'import java.nio.file.FileSystems;'
        'import java.nio.file.Files;'
        'import java.nio.file.Path;'
        'import java.nio.file.Paths;'
        'import java.util.Collections;'
        'import javax.xml.parsers.DocumentBuilderFactory;'
        'import javax.xml.transform.TransformerFactory;'
        'import javax.xml.transform.dom.DOMSource;'
        'import javax.xml.transform.stream.StreamResult;'
        'import org.w3c.dom.Document;'
        'import org.w3c.dom.Element;'
        'import org.w3c.dom.Node;'
        'import org.w3c.dom.NodeList;'
        ''
        'public class RestoreResultSelections {'
        '  // COMSOL validates solution indices against computed solutions in the API.'
        '  // Write the authored selections into the exported, unsolved model.'
        '  public static void main(String[] args) throws Exception {'
        '    Path file = Paths.get(args[0]).toAbsolutePath();'
        '    String[][] selections = {'
        '      {"ResultFeature", "pgStop", "p:solnum", "T", "30", "value", "2", "CompositeIndex", "1"},'
        '      {"ResultFeature", "pgStop", "p:showlooplevel", "T", "30", "valueMatrix", "1|3,''on'',''off'',''off''"},'
