        '          value.setAttribute(selection[index], selection[index + 1]);'
        '        }'
        '        replaceProperty(feature, value);'
        '      }'
        '      try (OutputStream output = Files.newOutputStream(modelFile)) {'
        '        TransformerFactory.newInstance().newTransformer()'
        '            .transform(new DOMSource(model), new StreamResult(output));'
        '      }'
        '    }'
        '  }'
        ''
        '  private static Element findFeature(Document model, String kind, String tag) {'
        '    NodeList features = model.getElementsByTagName(kind);'
        '    for (int index = 0; index < features.getLength(); index++) {'
