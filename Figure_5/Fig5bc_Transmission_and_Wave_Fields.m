% Compact COMSOL model. Run this script in MATLAB to export the MPH beside it.
% The script builds the geometry and mesh and saves the model without solving.
% Requires COMSOL Multiphysics 6.4. COMSOL_ROOT can override its location.

exportComsolModel(fileparts(mfilename('fullpath')), 'Fig5bc_Transmission_and_Wave_Fields.mph');

function exportComsolModel(outputDir, outputName)
    comsolBin = findComsolBin();
    workDir = tempname;
    [created, message] = mkdir(workDir);
    if ~created
        error('ComsolExport:TempDirectory', '%s', message);
    end
    originalDir = pwd;
    cleanup = onCleanup(@() cleanWorkDir(originalDir, workDir));
    cd(workDir);

    writeModelCode('ExportedModel.java');
    compileExe = fullfile(comsolBin, 'comsolcompile.exe');
    [status, output] = system(sprintf('"%s" ExportedModel.java', compileExe));
    if status ~= 0 || ~isfile('ExportedModel.class')
        error('ComsolExport:CompileFailed', 'COMSOL compilation failed.\n%s', output);
    end

    batchExe = fullfile(comsolBin, 'comsolbatch.exe');
    [status, output] = system(sprintf( ...
        '"%s" -np 2 -inputfile ExportedModel.class -nosave -batchlog rebuild.log', batchExe));
    if status ~= 0 || ~isfile(outputName)
        if isfile('rebuild.log')
            output = [output, newline, fileread('rebuild.log')];
        end
        error('ComsolExport:RebuildFailed', 'COMSOL export failed.\n%s', output);
    end

    writeResultSelectionCode('RestoreResultSelections.java');
    [status, output] = system(sprintf('"%s" RestoreResultSelections.java', compileExe));
    if status ~= 0 || ~isfile('RestoreResultSelections.class')
        error('ComsolExport:SelectionCompileFailed', 'Could not compile the result selector.\n%s', output);
    end
    javaExe = fullfile(comsolBin, '..', '..', 'java', 'win64', 'jre', 'bin', 'java.exe');
    [status, output] = system(sprintf( ...
        '"%s" -cp . RestoreResultSelections "%s"', javaExe, outputName));
    if status ~= 0
        error('ComsolExport:SelectionFailed', 'Could not save result selections.\n%s', output);
    end

    outputFile = fullfile(outputDir, outputName);
    [saved, message] = movefile(fullfile(workDir, outputName), outputFile, 'f');
    if ~saved
        error('ComsolExport:SaveFailed', 'Could not save %s.\n%s', outputFile, message);
    end
    fprintf('Saved COMSOL model to %s\n', outputFile);
end

function comsolBin = findComsolBin()
    candidates = {getenv('COMSOL_ROOT'), ...
        registeredComsolRoot(), ...
        fullfile(getenv('ProgramFiles'), 'COMSOL', 'COMSOL64', 'Multiphysics')};
    for index = 1:numel(candidates)
        if isempty(candidates{index})
            continue;
        end
        comsolBin = fullfile(candidates{index}, 'bin', 'win64');
        if isfile(fullfile(comsolBin, 'comsolcompile.exe')) && ...
                isfile(fullfile(comsolBin, 'comsolbatch.exe'))
            return;
        end
    end
    error('ComsolExport:ComsolNotFound', ...
        'Set COMSOL_ROOT to the COMSOL 6.4 Multiphysics installation directory.');
end

function root = registeredComsolRoot()
    root = '';
    if ispc
        try
            root = winqueryreg('HKEY_LOCAL_MACHINE', 'SOFTWARE\Comsol\COMSOL64', 'COMSOLROOT');
        catch
            % Use the standard installation path if COMSOL is not registered.
        end
    end
end

function cleanWorkDir(originalDir, workDir)
    cd(originalDir);
    rmdir(workDir, 's');
end

